// Generates JSX code string for a single component
function generateComponentJsx(type: string, props: any): string {
  const propsStr = JSON.stringify(props, null, 4)
    .replace(/"([^"]+)":/g, "$1:") // remove quotes from keys
    .replace(/"/g, "'");           // double quotes → single quotes

  return `<${type}\n  {...${propsStr}}\n/>`;
}

// Generates the App.jsx content
function generateAppJsx(components: any[], projectName: string): string {
  const imports = [...new Set(components.map((c) => c.type))]
    .map((type) => `import { ${type} } from './components/${type}';`)
    .join("\n");

  const sectionJsx = components
    .map((c) => `      ${generateComponentJsx(c.type, c.props || {})}`)
    .join("\n\n");

  return `import React from 'react';
${imports}

// Generated by AI Landing Page Builder
// Project: ${projectName}

export default function LandingPage() {
  return (
    <main>
${sectionJsx}
    </main>
  );
}
`;
}

