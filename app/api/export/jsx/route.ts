export async function GET(req: NextRequest) {
  try {
    const projectId = req.nextUrl.searchParams.get("id");
    if (!projectId) return NextResponse.json({ error: "Missing id" }, { status: 400 });

    const project = await prisma.project.findUnique({
      where: { id: projectId },
      include: { landingPage: true },
    });

    if (!project || !project.landingPage) {
      return NextResponse.json({ error: "Project not found" }, { status: 404 });
    }

    const components: any[] = (project.landingPage.content as any)?.components || [];
    const projectName = project.name || "landing-page";

    // Build ZIP
    const zip = new JSZip();

    // Root files
    zip.file("index.html", generateIndexHtml(projectName));
    zip.file("package.json", generatePackageJson(projectName));
    zip.file("vite.config.js", generateViteConfig());
    zip.file("README.md", generateReadme(projectName, components));

    // src/
    const src = zip.folder("src")!;
    src.file("main.jsx", generateMainJsx());
    src.file("App.jsx", generateAppJsx(components, projectName));
    src.file("index.css", generateIndexCss());

    // src/components/ — stub for each unique section type
    const componentsFolder = src.folder("components")!;
    const uniqueTypes = [...new Set(components.map((c) => c.type))];
    for (const type of uniqueTypes) {
      componentsFolder.file(`${type}.jsx`, generateStubComponent(type));
    }

    // Also save the raw page data as JSON
    src.file("page-data.json", JSON.stringify(components, null, 2));

    const zipBuffer = await zip.generateAsync({ type: "arraybuffer", compression: "DEFLATE" });
    const safeName = projectName.replace(/[^a-z0-9]/gi, "-").toLowerCase();

    return new NextResponse(zipBuffer as unknown as BodyInit, {
      status: 200,
      headers: {
        "Content-Type": "application/zip",
        "Content-Disposition": `attachment; filename="${safeName}.zip"`,
      },
    });
  } catch (err) {
    console.error("[export/jsx]", err);
    return NextResponse.json({ error: "Internal Server Error" }, { status: 500 });
  }
}
